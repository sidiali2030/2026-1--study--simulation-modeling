# # Формирование итоговых графиков для модели SIR
#
# В данном разделе выполняется загрузка ранее сохранённых результатов
# моделирования модели SIR и построение итоговых графиков для отчёта.
#
# Используются три набора данных:
#
# - результаты детерминированной симуляции;
# - результаты стохастической симуляции;
# - результаты анализа чувствительности по параметру `β`.
#
# На основе этих данных строятся два графика:
#
# 1. сравнение детерминированной и стохастической динамики инфицированных;
# 2. зависимость максимального числа инфицированных от коэффициента заражения `β`.


# ## Подключение библиотеки DrWatson
#
# Пакет `DrWatson` используется для организации структуры проекта
# и удобной работы с каталогами `data` и `plots`.

using DrWatson

# Активируем окружение проекта.

@quickactivate "project"

# Подключаем необходимые библиотеки:
#
# - `DataFrames` — для работы с табличными данными;
# - `CSV` — для чтения ранее сохранённых CSV-файлов;
# - `Plots` — для построения графиков.

using DataFrames, CSV, Plots


# ## Загрузка результатов моделирования
#
# Загружаем результаты детерминированной симуляции
# из файла `data/sir_det.csv`.

df_det = CSV.read(datadir("sir_det.csv"), DataFrame)

# Загружаем результаты стохастической симуляции
# из файла `data/sir_stoch.csv`.

df_stoch = CSV.read(datadir("sir_stoch.csv"), DataFrame)

# Загружаем результаты сканирования параметра `β`
# из файла `data/sir_scan.csv`.

df_scan = CSV.read(datadir("sir_scan.csv"), DataFrame)


# ## Сравнение детерминированной и стохастической динамики
#
# Первый график используется для сравнения динамики
# количества инфицированных `I` в двух вариантах модели:
#
# - детерминированной;
# - стохастической.
#
# По горизонтальной оси отображается время моделирования,
# а по вертикальной — количество инфицированных.
#
# Детерминированная траектория берётся из `df_det.I`.
#
# Для стохастической траектории используется соответствующий
# фрагмент `df_stoch.I`, длина которого ограничивается
# количеством временных точек детерминированной симуляции.

# Сравнение детерминированной и стохастической динамики
p1 = plot(
df_det.time,
[df_det.I df_stoch.I[1:length(df_det.time)]],
label = ["Deterministic I" "Stochastic I"],
xlabel = "Time",
ylabel = "Infected",
title = "Comparison",
)

# Сохраняем построенный сравнительный график
# в каталог `plots` под именем:
#
# `comparison.png`

savefig(plotsdir("comparison.png"))


# ## Анализ чувствительности модели
#
# Второй график показывает зависимость максимального количества
# инфицированных `Peak I` от коэффициента заражения `β`.
#
# Значения `β` берутся из столбца `df_scan.β`,
# а соответствующие значения пика инфекции —
# из столбца `df_scan.peak_I`.
#
# Такой график позволяет оценить, как изменение коэффициента
# заражения влияет на максимальную величину эпидемической волны.

# Зависимость пика I от β
p2 = plot(
df_scan.β,
df_scan.peak_I,
marker = :circle,
xlabel = "β",
ylabel = "Peak I",
title = "Sensitivity",
)

# Сохраняем график чувствительности
# в каталог `plots` под именем:
#
# `sensitivity.png`

savefig(plotsdir("sensitivity.png"))


# ## Результат выполнения
#
# После успешного выполнения программы в каталоге `plots`
# будут созданы два итоговых изображения:
#
# - `comparison.png` — сравнение детерминированной
#   и стохастической динамики;
# - `sensitivity.png` — зависимость пика инфицированных
#   от коэффициента заражения `β`.
#
# Эти графики могут быть использованы в итоговом отчёте
# по лабораторной работе.

println("Отчётные графики сохранены в plots/")
