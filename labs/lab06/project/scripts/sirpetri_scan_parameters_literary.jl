# # Исследование влияния коэффициента заражения β
#
# В данном фрагменте выполняется анализ чувствительности модели SIR
# к изменению коэффициента заражения `β`.
#
# Основная цель эксперимента — определить, как изменение параметра `β`
# влияет на максимальное число инфицированных `peak_I`
# и итоговое число выздоровевших `final_R`.
#
# Для каждого значения `β` выполняется отдельная детерминированная
# симуляция модели SIR, после чего основные показатели сохраняются
# в таблицу и визуализируются на графике.

using DrWatson

# Активируем окружение проекта `project`.
# Пакет DrWatson используется для удобной организации структуры проекта
# и работы с каталогами `src`, `data` и `plots`.

@quickactivate "project"

# Подключаем основной файл, содержащий реализацию модели SIR
# на основе сети Петри.

include(srcdir("SIRPetri.jl"))

# Подключаем модуль SIRPetri, функции которого будут использоваться
# для построения сети и выполнения моделирования.

using .SIRPetri

# Подключаем библиотеки:
#
# - `DataFrames` — для хранения результатов эксперимента в табличном виде;
# - `CSV` — для сохранения результатов в CSV-файл;
# - `Plots` — для построения графиков.

using DataFrames, CSV, Plots

# ## Диапазон коэффициента заражения β
#
# Задаётся набор значений параметра `β`,
# для которых будет выполнено моделирование.
#
# Начальное значение равно `0.1`,
# шаг изменения равен `0.05`,
# конечное значение равно `0.8`.

# Диапазон β
β_range = 0.1:0.05:0.8

# Коэффициент выздоровления `γ` остаётся фиксированным
# на протяжении всего эксперимента.

γ_fixed = 0.1

# Максимальное время моделирования.

tmax = 100.0

# Создаём пустой массив, в который будут последовательно
# добавляться результаты каждого запуска модели.

results = []

# ## Последовательное моделирование для разных значений β
#
# Цикл проходит по всем значениям коэффициента заражения,
# определённым в `β_range`.
#
# Для каждого значения `β` создаётся сеть Петри,
# выполняется детерминированная симуляция,
# вычисляется максимальное число инфицированных
# и конечное число выздоровевших.

for β in β_range

net, u0, _ = build_sir_network(β, γ_fixed)

df = simulate_deterministic(net, u0, (0.0, tmax), saveat = 0.5, rates = [β, γ_fixed])

peak_I = maximum(df.I)


final_R = df.R[end]


push!(results, (β = β, peak_I = peak_I, final_R = final_R))

end

# ## Формирование таблицы результатов
#
# После завершения всех симуляций преобразуем массив `results`
# в объект `DataFrame`.
#
# Итоговая таблица содержит три столбца:
#
# - `β`;
# - `peak_I`;
# - `final_R`.

df_scan = DataFrame(results)

# Сохраняем полученную таблицу в CSV-файл.
#
# Файл будет расположен в каталоге:
#
# `data/sir_scan.csv`

CSV.write(datadir("sir_scan.csv"), df_scan)

# ## Визуализация результатов
#
# Строим график зависимости основных показателей модели
# от коэффициента заражения `β`.
#
# На одном графике отображаются две зависимости:
#
# - `Peak I` — максимальное количество инфицированных;
# - `Final R` — конечное количество выздоровевших.

# График
p = plot(
df_scan.β,
[df_scan.peak_I df_scan.final_R],
label = ["Peak I" "Final R"],
marker = :circle,
xlabel = "β (infection rate)",
ylabel = "Population",
)

# Сохраняем построенный график в каталог `plots`.
#
# Имя файла:
#
# `sir_scan.png`

savefig(plotsdir("sir_scan.png"))

# ## Завершение эксперимента
#
# После успешного выполнения программы выводится сообщение
# о завершении сканирования параметра `β`.
#
# Основные результаты сохранены в:
#
# - `data/sir_scan.csv`;
# - `plots/sir_scan.png`.

println("Сканирование β завершено. Результат в data/sir_scan.csv")
