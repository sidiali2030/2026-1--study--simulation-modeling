# # Исследование влияния коэффициента заражения β на модель SIR
#
# В данном эксперименте исследуется влияние коэффициента заражения `β`
# на динамику эпидемиологической модели SIR, реализованной с помощью
# сетей Петри.
#
# Для различных значений коэффициента `β` выполняется
# детерминированная симуляция модели.
#
# Для каждого эксперимента определяются два основных показателя:
#
# - `peak_I` — максимальное количество инфицированных;
# - `final_R` — количество выздоровевших в конце моделирования.
#
# Полученные результаты сохраняются в CSV-файл и используются
# для построения графика зависимости характеристик эпидемии
# от коэффициента заражения.


# ## Подключение необходимых библиотек
#
# Пакет `DrWatson` используется для организации структуры проекта
# и удобного доступа к каталогам проекта.

using DrWatson

# Активируем окружение проекта.

@quickactivate "project"

# Подключаем файл `SIRPetri.jl`, содержащий реализацию модели SIR
# на основе сети Петри.

include(srcdir("SIRPetri.jl"))

# Подключаем модуль SIRPetri.

using .SIRPetri

# Подключаем дополнительные библиотеки:
#
# - `DataFrames` — для представления результатов в виде таблицы;
# - `CSV` — для сохранения результатов;
# - `Plots` — для визуализации результатов.

using DataFrames, CSV, Plots


# ## Задание параметров эксперимента
#
# Исследование выполняется для диапазона значений коэффициента
# заражения `β` от 0.1 до 0.8 с шагом 0.05.

# Диапазон β
β_range = 0.1:0.05:0.8

# Коэффициент выздоровления `γ` во всех экспериментах
# остаётся постоянным и равен 0.1.

γ_fixed = 0.1

# Максимальное время моделирования составляет 100
# единиц модельного времени.

tmax = 100.0

# Создаём пустой массив для хранения результатов
# всех выполненных экспериментов.

results = []


# ## Выполнение серии экспериментов
#
# Последовательно перебираем все значения `β`
# из заданного диапазона.

for β in β_range



net, u0, _ = build_sir_network(β, γ_fixed)


df = simulate_deterministic(net, u0, (0.0, tmax), saveat = 0.5, rates = [β, γ_fixed])


peak_I = maximum(df.I)


final_R = df.R[end]


push!(results, (β = β, peak_I = peak_I, final_R = final_R))

end


# ## Формирование таблицы результатов
#
# После выполнения всех экспериментов массив `results`
# преобразуется в таблицу `DataFrame`.
#
# Таблица будет содержать следующие столбцы:
#
# | β | peak_I | final_R |
# |---|--------|---------|
# | коэффициент заражения | пик инфицированных | итоговое число выздоровевших |

df_scan = DataFrame(results)


# ## Сохранение результатов
#
# Полученная таблица сохраняется в CSV-файл:
#
# `data/sir_scan.csv`
#
# Функция `datadir` из пакета DrWatson автоматически
# формирует путь к каталогу `data` проекта.

CSV.write(datadir("sir_scan.csv"), df_scan)


# ## Построение графика
#
# Теперь визуализируем полученные результаты.
#
# По горизонтальной оси отображается коэффициент заражения `β`.
#
# На графике одновременно представлены:
#
# - `Peak I` — максимальное количество инфицированных;
# - `Final R` — конечное количество выздоровевших.

# График
p = plot(
df_scan.β,
[df_scan.peak_I df_scan.final_R],
label = ["Peak I" "Final R"],
marker = :circle,
xlabel = "β (infection rate)",
ylabel = "Population",
)


# ## Сохранение графика
#
# Построенный график сохраняется в каталоге `plots`
# под именем:
#
# `sir_scan.png`

savefig(plotsdir("sir_scan.png"))


# ## Завершение эксперимента
#
# После завершения всех вычислений программа выводит
# сообщение об успешном выполнении сканирования параметра `β`.
#
# В результате работы программы создаются:
#
# - `data/sir_scan.csv` — таблица результатов;
# - `plots/sir_scan.png` — график зависимости результатов от `β`.
#
# Полученные данные позволяют оценить влияние изменения
# коэффициента заражения на развитие эпидемического процесса.

println("Сканирование β завершено. Результат в data/sir_scan.csv")
