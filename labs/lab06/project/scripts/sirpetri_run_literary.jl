# # Базовый запуск модели SIR на основе сетей Петри
#
# В данной работе рассматривается эпидемиологическая модель SIR
# (Susceptible – Infectious – Recovered), реализованная с использованием
# подхода сетей Петри.
#
# Модель содержит три состояния:
#
# - `S` — восприимчивые к инфекции;
# - `I` — инфицированные;
# - `R` — выздоровевшие.
#
# В модели рассматриваются два основных процесса:
#
# 1. заражение:
#
# ```text
# S + I → I + I
# ```
#
# 2. выздоровление:
#
# ```text
# I → R
# ```
#
# Цель данного скрипта — выполнить базовый запуск модели,
# провести детерминированное и стохастическое моделирование,
# сохранить результаты в формате CSV и построить графики динамики
# состояний `S`, `I` и `R`.


# ## Подключение библиотек
#
# Для организации структуры проекта используется пакет `DrWatson`.
# Макрос `@quickactivate` активирует окружение проекта и позволяет
# использовать функции `srcdir`, `datadir` и `plotsdir` для работы
# с каталогами проекта.

using DrWatson
@quickactivate "project"

# Пакет `Random` используется для управления генератором случайных чисел.
# Это необходимо для воспроизводимости стохастической симуляции.

using Random

# Подключаем основной модуль модели SIR.
# Файл `SIRPetri.jl` расположен в каталоге `src`.

include(srcdir("SIRPetri.jl"))
using .SIRPetri

# `DataFrames` используется для хранения табличных результатов,
# `CSV` — для записи результатов в CSV-файлы,
# `Plots` — для построения и сохранения графиков.

using DataFrames
using CSV
using Plots


# ## Параметры модели
#
# Зададим основные параметры эпидемиологической модели.
#
# Параметр `β` характеризует интенсивность заражения.
#
# Параметр `γ` характеризует интенсивность выздоровления.
#
# Параметр `tmax` определяет продолжительность моделирования.

β = 0.3
γ = 0.1
tmax = 100.0


# ## Построение сети Петри
#
# С помощью функции `build_sir_network` создаётся размеченная сеть Петри.
#
# Функция возвращает:
#
# - `net` — объект сети Петри;
# - `u0` — начальную маркировку сети;
# - `states` — список состояний модели.
#
# Начальная маркировка соответствует:
#
# ```text
# S₀ = 990
# I₀ = 10
# R₀ = 0
# ```
#
# Таким образом, в начале моделирования имеется 990 восприимчивых,
# 10 инфицированных и ни одного выздоровевшего.

net, u0, states = build_sir_network(β, γ)


# ## Детерминированная симуляция
#
# Сначала выполняется детерминированное моделирование.
#
# В данном случае динамика системы описывается системой
# обыкновенных дифференциальных уравнений.
#
# Для численного решения используется временной интервал
# от `0` до `tmax`.
#
# Параметр `saveat = 0.5` означает, что значения решения
# сохраняются через каждые 0.5 единицы времени.

df_det = simulate_deterministic(
    net,
    u0,
    (0.0, tmax);
    saveat = 0.5,
    rates = [β, γ],
)


# ### Сохранение детерминированных результатов
#
# Полученные данные сохраняются в файл:
#
# ```text
# data/sir_det.csv
# ```
#
# Таблица содержит столбцы:
#
# - `time`;
# - `S`;
# - `I`;
# - `R`.

CSV.write(datadir("sir_det.csv"), df_det)


# ## Стохастическая симуляция
#
# Далее выполняется стохастическая симуляция модели.
#
# В отличие от детерминированного подхода, стохастическая модель
# учитывает случайный характер событий заражения и выздоровления.
#
# Перед запуском задаётся фиксированное зерно генератора
# случайных чисел:
#
# ```text
# seed = 123
# ```
#
# Это позволяет получить одинаковую случайную траекторию
# при повторном запуске программы.

Random.seed!(123)


# Выполняем стохастическое моделирование на том же временном интервале.

df_stoch = simulate_stochastic(
    net,
    u0,
    (0.0, tmax);
    rates = [β, γ],
)


# ### Сохранение стохастических результатов
#
# Результаты записываются в файл:
#
# ```text
# data/sir_stoch.csv
# ```

CSV.write(datadir("sir_stoch.csv"), df_stoch)


# ## Визуализация детерминированной динамики
#
# Построим график изменения количества восприимчивых,
# инфицированных и выздоровевших во времени.

p_det = plot_sir(df_det)

# График сохраняется в каталоге `plots` под именем:
#
# ```text
# sir_det_dynamics.png
# ```

savefig(p_det, plotsdir("sir_det_dynamics.png"))


# ## Визуализация стохастической динамики
#
# Аналогичным образом строится график для стохастической
# траектории модели.

p_stoch = plot_sir(df_stoch)

# Результат сохраняется в файл:
#
# ```text
# plots/sir_stoch_dynamics.png
# ```

savefig(p_stoch, plotsdir("sir_stoch_dynamics.png"))


# ## Результаты выполнения
#
# После успешного завершения программы будут созданы следующие файлы:
#
# ```text
# data/
# ├── sir_det.csv
# └── sir_stoch.csv
#
# plots/
# ├── sir_det_dynamics.png
# └── sir_stoch_dynamics.png
# ```
#
# Детерминированная модель показывает усреднённую плавную динамику
# эпидемического процесса, тогда как стохастическая модель позволяет
# наблюдать случайные отклонения, возникающие вследствие дискретного
# характера событий.
#
# Выводим сообщение об успешном завершении базового эксперимента.

println("Базовый прогон завершён. Результаты в data/ и plots/")
