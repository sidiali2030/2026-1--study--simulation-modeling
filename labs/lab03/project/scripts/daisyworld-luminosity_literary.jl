# # Динамика модели Daisyworld
#
# В данном эксперименте исследуется комплексная динамика модели Daisyworld.
#
# Анализируется изменение во времени:
#
# - количества чёрных маргариток;
# - количества белых маргариток;
# - средней температуры поверхности;
# - солнечной светимости.
#
# Моделирование выполняется в течение 1000 модельных шагов.
# Для изменения солнечной светимости используется сценарий `:ramp`.

using DrWatson
@quickactivate "project"
using Agents
using DataFrames
using Plots
include(srcdir("daisyworld.jl"))
using CairoMakie

# ## Определение типов маргариток
#
# Определяем функции, позволяющие определить принадлежность
# каждого агента к чёрному или белому типу маргариток.

black(a) = a.breed == :black
white(a) = a.breed == :white

# ## Сбор данных об агентах
#
# В массиве `adata` задаём показатели, которые необходимо собирать
# во время моделирования.
#
# Для каждого момента времени будет подсчитываться количество
# чёрных и белых маргариток.

adata = [(black, count), (white, count)]

# ## Инициализация модели
#
# Создаём модель Daisyworld с начальным значением солнечной
# светимости `1.0`.
#
# Параметр `scenario = :ramp` задаёт сценарий изменения
# солнечной светимости во времени.

model = daisyworld(solar_luminosity = 1.0, scenario = :ramp)

# ## Средняя температура модели
#
# Определяем функцию для вычисления средней температуры
# поверхности всей модели.

temperature(model) = StatsBase.mean(model.temperature)

# ## Сбор данных модели
#
# Помимо данных об агентах необходимо сохранить среднюю
# температуру и текущее значение солнечной светимости.

mdata = [temperature, :solar_luminosity]

# ## Выполнение моделирования
#
# Запускаем модель на 1000 шагов.
#
# В `agent_df` сохраняются данные о количестве чёрных и белых
# маргариток, а в `model_df` — температура и солнечная светимость.

agent_df, model_df = run!(model, 1000; adata = adata, mdata = mdata)

# ## Создание комплексного графика
#
# Создаём фигуру размером 600×600 пикселей.
# На ней будут расположены три графика.

figure = CairoMakie.Figure(size = (600, 600));

# ## Динамика количества маргариток
#
# Первый график показывает изменение количества маргариток
# каждого типа в зависимости от модельного времени.

ax1 = figure[1, 1] = Axis(figure, ylabel = "daisy count")

blackl = lines!(
    ax1,
    agent_df[!, :time],
    agent_df[!, :count_black],
    color = :red
)

whitel = lines!(
    ax1,
    agent_df[!, :time],
    agent_df[!, :count_white],
    color = :blue
)

# Добавляем легенду, обозначающую чёрные и белые маргаритки.

figure[1, 2] = Legend(
    figure,
    [blackl, whitel],
    ["black", "white"]
)

# ## Динамика температуры
#
# Второй график предназначен для отображения изменения
# средней температуры поверхности модели.

ax2 = figure[2, 1] = Axis(
    figure,
    ylabel = "temperature"
)

# ## Динамика солнечной светимости
#
# Третий график показывает изменение солнечной светимости
# во времени.

ax3 = figure[3, 1] = Axis(
    figure,
    xlabel = "tick",
    ylabel = "luminosity"
)

# Строим график изменения средней температуры поверхности.

lines!(
    ax2,
    model_df[!, :time],
    model_df[!, :temperature],
    color = :red
)

# Строим график изменения солнечной светимости.

lines!(
    ax3,
    model_df[!, :time],
    model_df[!, :solar_luminosity],
    color = :red
)

# Для первых двух графиков скрываем подписи значений
# горизонтальной оси, поскольку общая временная шкала
# представлена на нижнем графике.

for ax in (ax1, ax2); ax.xticklabelsvisible = false; end

figure

# ## Сохранение результата
#
# Сохраняем полученный комплексный график в каталог `plots`
# под именем `daisy_luminosity.png`.

save(plotsdir("daisy_luminosity.png"), figure)

# ## Анализ результата
#
# На полученном рисунке можно проследить взаимосвязь между
# солнечной светимостью, температурой поверхности и численностью
# двух типов маргариток.
#
# В начальной части моделирования при солнечной светимости,
# близкой к 1.0, в системе существуют обе популяции.
# Численность чёрных и белых маргариток значительно колеблется,
# а средняя температура поверхности изменяется приблизительно
# в диапазоне от 8 до более 30 градусов.
#
# После начала увеличения солнечной светимости температура
# поверхности также постепенно возрастает.
#
# В этот период количество чёрных маргариток начинает уменьшаться.
# При дальнейшем увеличении светимости их численность резко падает,
# и приблизительно после 300 модельных шагов чёрные маргаритки
# практически полностью исчезают из системы.
#
# Одновременно численность белых маргариток значительно возрастает
# и достигает почти максимального заполнения доступной поверхности.
# После этого белые маргаритки становятся доминирующим типом
# в модели.
#
# При максимальной солнечной светимости температура поверхности
# стабилизируется примерно около 30 градусов, а количество белых
# маргариток остаётся высоким.
#
# После уменьшения солнечной светимости, начиная примерно
# с 500-го модельного шага, средняя температура постепенно
# снижается. Несмотря на это, белые маргаритки продолжают
# преобладать, тогда как популяция чёрных маргариток
# не восстанавливается.
#
# На последнем участке моделирования солнечная светимость
# стабилизируется, а температура поверхности демонстрирует
# периодические колебания. Аналогичные кратковременные колебания
# наблюдаются и в численности белых маргариток.
#
# ## Вывод
#
# Полученные результаты показывают, что изменение солнечной
# светимости существенно влияет на состояние экосистемы Daisyworld.
# При увеличении светимости условия становятся неблагоприятными
# для чёрных маргариток, в результате чего их популяция исчезает,
# тогда как белые маргаритки получают преимущество и начинают
# доминировать.
#
# Изменение состава популяции связано с изменением температуры
# поверхности. Таким образом, модель демонстрирует взаимосвязь
# между внешним воздействием, температурой среды и динамикой
# популяций агентов.
