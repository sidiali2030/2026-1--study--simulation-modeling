# # Динамика модели Daisyworld для набора параметров
#
# В данном эксперименте исследуется комплексная динамика модели
# Daisyworld для нескольких комбинаций параметров.
#
# Для каждого набора параметров анализируется изменение:
#
# - количества чёрных маргариток;
# - количества белых маргариток;
# - средней температуры поверхности;
# - солнечной светимости.
#
# Моделирование выполняется в течение 1000 модельных шагов.
# Для изменения солнечной светимости используется сценарий `:ramp`.

using DrWatson
@quickactivate "project"
using Agents
using DataFrames
using Plots
using CairoMakie
include(srcdir("daisyworld.jl"))

# ## Определение типов маргариток
#
# Определяем функции, позволяющие определить принадлежность
# каждого агента к чёрному или белому типу маргариток.

black(a) = a.breed == :black
white(a) = a.breed == :white

# ## Сбор данных об агентах
#
# В `adata` задаём показатели, которые будут собираться
# во время моделирования.
#
# Для каждого момента времени будет подсчитываться количество
# чёрных и белых маргариток.

adata = [(black, count), (white, count)]

# ## Параметры эксперимента
#
# Формируем словарь параметров модели.
#
# В серии экспериментов изменяются два параметра:
#
# - `max_age` принимает значения 25 и 40;
# - `init_white` принимает значения 0.2 и 0.8.
#
# Остальные параметры остаются постоянными.
#
# Сценарий `:ramp` используется для изменения солнечной
# светимости в процессе моделирования.

param_dict = Dict(
:griddims => (30, 30),
:max_age => [25, 40],
:init_white => [0.2, 0.8],
:init_black => 0.2,
:albedo_white => 0.75,
:albedo_black => 0.25,
:surface_albedo => 0.4,
:solar_change => 0.005,
:solar_luminosity => 1.0,
:scenario => :ramp,
:seed => 165,
)

# ## Формирование комбинаций параметров
#
# С помощью функции `dict_list` создаём список всех возможных
# комбинаций значений параметров.
#
# Так как изменяются два параметра, каждый из которых имеет
# по два значения, всего формируется четыре набора параметров.

params_list = dict_list(param_dict)

# ## Выполнение серии экспериментов
#
# Для каждого набора параметров создаётся отдельная модель.
#
# В ходе моделирования собираются данные о численности агентов,
# средней температуре поверхности и солнечной светимости.
#
# Вся конструкция `for ... end` сохраняется в одном блоке,
# что важно при последующем выполнении кода в Jupyter notebook.

for params in params_list

    model = daisyworld(;params...)

    temperature(model) = StatsBase.mean(model.temperature)

    mdata = [temperature, :solar_luminosity]

    agent_df, model_df = run!(
        model,
        1000;
        adata = adata,
        mdata = mdata
    )

    figure = CairoMakie.Figure(size = (600, 600));

    ax1 = figure[1, 1] = Axis(
        figure,
        ylabel = "daisy count"
    )

    blackl = lines!(
        ax1,
        agent_df[!, :time],
        agent_df[!, :count_black],
        color = :red
    )

    whitel = lines!(
        ax1,
        agent_df[!, :time],
        agent_df[!, :count_white],
        color = :blue
    )

    figure[1, 2] = Legend(
        figure,
        [blackl, whitel],
        ["black", "white"]
    )

    ax2 = figure[2, 1] = Axis(
        figure,
        ylabel = "temperature"
    )

    ax3 = figure[3, 1] = Axis(
        figure,
        xlabel = "tick",
        ylabel = "luminosity"
    )

    lines!(
        ax2,
        model_df[!, :time],
        model_df[!, :temperature],
        color = :red
    )

    lines!(
        ax3,
        model_df[!, :time],
        model_df[!, :solar_luminosity],
        color = :red
    )

    for ax in (ax1, ax2); ax.xticklabelsvisible = false; end

    plt_name = savename("daisy-luminosity",params)

    save(plotsdir(plt_name * ".png"), figure)

end

# ## Анализ результата
#
# В результате эксперимента были получены комплексные графики
# динамики модели Daisyworld для четырёх комбинаций параметров:
#
# - `max_age = 25`, `init_white = 0.2`;
# - `max_age = 40`, `init_white = 0.2`;
# - `max_age = 25`, `init_white = 0.8`;
# - `max_age = 40`, `init_white = 0.8`.
#
# Каждый график содержит три взаимосвязанных характеристики:
# численность маргариток, среднюю температуру поверхности
# и солнечную светимость.
#
# Изменение `init_white` влияет на начальное соотношение
# популяций. При большем значении этого параметра модель
# начинает работу с существенно большей долей белых маргариток.
#
# Изменение `max_age` влияет на продолжительность жизни
# агентов и, следовательно, на дальнейшую динамику численности
# обеих популяций.
#
# В сценарии `:ramp` солнечная светимость изменяется во времени.
# Это приводит к изменению средней температуры поверхности,
# что, в свою очередь, изменяет условия существования
# чёрных и белых маргариток.
#
# Сравнение результатов для различных наборов параметров
# позволяет наблюдать, как начальное состояние и максимальный
# возраст агентов влияют на реакцию модели на внешнее
# изменение солнечной светимости.
#
# Использование одинакового значения `seed = 165` обеспечивает
# воспроизводимость серии вычислительных экспериментов.

# ## Вывод
#
# Параметрический эксперимент показывает, что поведение
# Daisyworld определяется совместным влиянием параметров агентов
# и изменения внешней среды.
#
# Начальная доля белых маргариток влияет на исходное состояние
# популяций, а максимальный возраст агентов изменяет характер
# их дальнейшего развития.
#
# Одновременно сценарий изменения солнечной светимости приводит
# к изменению температуры поверхности и создаёт различные условия
# для существования двух типов маргариток.
#
# Таким образом, анализ нескольких комбинаций параметров
# позволяет более полно исследовать устойчивость и динамику
# модели Daisyworld и оценить влияние параметров модели
# на её реакцию при изменении внешних условий.
#
# Использование `dict_list` и `savename` из DrWatson позволяет
# автоматизировать серию экспериментов и сохранять каждый
# полученный график с указанием соответствующего набора параметров.
