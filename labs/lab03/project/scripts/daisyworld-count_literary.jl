# # Динамика числа маргариток
#
# В данном эксперименте исследуется изменение числа чёрных и белых
# маргариток в модели Daisyworld в зависимости от модельного времени.
#
# Для этого запускается модель на 1000 шагов, на каждом шаге
# подсчитывается количество маргариток каждого типа, после чего
# строится график их динамики.

using DrWatson
@quickactivate "project"
using Agents
using DataFrames
using Plots
include(srcdir("daisyworld.jl"))
using CairoMakie

# ## Определение типов маргариток
#
# Определяем две функции для проверки типа агента.
# Функция `black` возвращает истинное значение для чёрной маргаритки,
# а функция `white` — для белой.

black(a) = a.breed == :black
white(a) = a.breed == :white

# ## Сбор данных
#
# Формируем набор данных `adata`, который будет использоваться
# для подсчёта количества чёрных и белых маргариток во время
# выполнения модели.

adata = [(black, count), (white, count)]

# ## Инициализация модели
#
# Создаём модель Daisyworld с начальной солнечной светимостью,
# равной `1.0`.

model = daisyworld(; solar_luminosity = 1.0)

# ## Выполнение моделирования
#
# Запускаем модель на 1000 модельных шагов.
# В процессе работы сохраняется количество маргариток каждого типа.
# Результаты сбора данных записываются в таблицу `agent_df`.

agent_df, model_df = run!(model, 1000; adata)

# ## Создание графика
#
# Создаём область для построения графика размером 600×400 пикселей.

figure = Figure(size = (600, 400));

# Задаём координатные оси.
# По горизонтальной оси отображается модельное время `tick`,
# а по вертикальной — количество маргариток.

ax = figure[1, 1] = Axis(figure, xlabel = "tick", ylabel = "daisy count")

# ## Динамика чёрных маргариток
#
# Строим линию, показывающую изменение количества чёрных
# маргариток во времени.

blackl = lines!(ax, agent_df[!, :time], agent_df[!, :count_black], color = :black)

# ## Динамика белых маргариток
#
# Аналогично строим линию изменения количества белых маргариток.
# Для лучшей видимости на графике используется оранжевый цвет.

whitel = lines!(ax, agent_df[!, :time], agent_df[!, :count_white], color = :orange)

# ## Легенда
#
# Добавляем обозначения линий для чёрных и белых маргариток.

Legend(figure[1, 2], [blackl, whitel], ["black", "white"], labelsize = 12)

# figure

# ## Сохранение результата
#
# Сохраняем полученный график в каталог `plots`
# под именем `daisy_count.png`.

save(plotsdir("daisy_count.png"), figure)

# ## Анализ результата
#
# На полученном графике показана динамика количества чёрных
# и белых маргариток на протяжении 1000 модельных шагов.
#
# В начальный период моделирования наблюдаются значительные
# колебания численности обеих популяций. Количество чёрных
# и белых маргариток быстро изменяется, достигая как высоких,
# так и низких значений.
#
# После начального переходного процесса обе популяции сохраняются
# в системе и продолжают колебаться. Численность чёрных маргариток
# в основном находится примерно в диапазоне от 400 до 550,
# хотя периодически наблюдаются более сильные отклонения.
#
# Количество белых маргариток также изменяется во времени
# и в большей части моделирования находится примерно в диапазоне
# от 350 до 500.
#
# Кривые неоднократно сближаются и пересекаются, поэтому ни один
# из видов не сохраняет постоянного абсолютного преимущества
# на всём интервале моделирования.
#
# Таким образом, модель демонстрирует динамическое сосуществование
# двух типов маргариток. Их численность не остаётся постоянной,
# а изменяется в результате процессов размножения, старения,
# гибели и взаимодействия с температурными условиями среды.
