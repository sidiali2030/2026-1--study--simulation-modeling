# # Базовая визуализация Daisyworld для набора параметров
#
# В данном эксперименте выполняется базовая визуализация модели
# Daisyworld для нескольких комбинаций параметров.
#
# В отличие от предыдущей базовой визуализации, здесь модель
# запускается не один раз, а для всех комбинаций значений
# `max_age` и `init_white`.
#
# Для каждой комбинации параметров сохраняются три состояния модели:
#
# - начальное состояние;
# - состояние после 5 модельных шагов;
# - состояние после следующих 40 модельных шагов.

using DrWatson
@quickactivate "project"
using Agents
using DataFrames
using Plots
using CairoMakie
include(srcdir("daisyworld.jl"))

# ## Параметры эксперимента
#
# Создаём словарь параметров модели.
#
# В данном эксперименте изменяются два параметра:
#
# - `max_age` принимает значения 25 и 40;
# - `init_white` принимает значения 0.2 и 0.8.
#
# Остальные параметры остаются постоянными.

param_dict = Dict(
:griddims => (30, 30),
:max_age => [25, 40],
:init_white => [0.2, 0.8],
:init_black => 0.2,
:albedo_white => 0.75,
:albedo_black => 0.25,
:surface_albedo => 0.4,
:solar_change => 0.005,
:solar_luminosity => 1.0,
:scenario => :default,
:seed => 165,
)

# ## Формирование комбинаций параметров
#
# Функция `dict_list` из DrWatson формирует список всех возможных
# комбинаций значений параметров, заданных в словаре.
#
# Поскольку изменяются два параметра, каждый из которых имеет
# по два значения, всего будет сформировано четыре комбинации.

params_list = dict_list(param_dict)

# ## Настройка отображения агентов
#
# Цвет каждой маргаритки определяется её типом `breed`.

daisycolor(a::Daisy) = a.breed

# ## Выполнение серии экспериментов
#
# Последовательно перебираем все наборы параметров.
# Для каждого набора создаётся отдельная модель Daisyworld.

for params in params_list

    model = daisyworld(;params...)

    plotkwargs = (
        agent_color=daisycolor,
        agent_size = 20,
        agent_marker = '✿',
        heatarray = :temperature,
        heatkwargs = (colorrange = (-20, 60),),
    )

    plt1, _ = abmplot(model; plotkwargs...)

    step!(model, 5)

    plt2, _ = abmplot(
        model;
        heatarray = model.temperature,
        plotkwargs...
    )

    step!(model, 40)

    plt3, _ = abmplot(
        model;
        heatarray = model.temperature,
        plotkwargs...
    )

    plt1_name = savename("daisyworld",params) * "_step01" * ".png"
    plt2_name = savename("daisyworld",params) * "_step05" * ".png"
    plt3_name = savename("daisyworld",params) * "_step40" * ".png"

    save(plotsdir(plt1_name), plt1)
    save(plotsdir(plt2_name), plt2)
    save(plotsdir(plt3_name), plt3)

end
# ## Анализ результата
#
# В результате выполнения эксперимента были рассмотрены четыре
# комбинации параметров `max_age` и `init_white`:
#
# - `max_age = 25`, `init_white = 0.2`;
# - `max_age = 40`, `init_white = 0.2`;
# - `max_age = 25`, `init_white = 0.8`;
# - `max_age = 40`, `init_white = 0.8`.
#
# Для каждой комбинации были получены три изображения,
# соответствующие различным моментам модельного времени.
# Таким образом, в результате эксперимента создано 12 изображений.
#
# По именам файлов видно, что DrWatson автоматически сохраняет
# значения всех параметров эксперимента. Это позволяет однозначно
# определить условия, при которых было получено каждое изображение.
#
# Значение `init_white` непосредственно влияет на начальное
# распределение агентов. При `init_white = 0.8` в начальном
# состоянии поверхность значительно сильнее заполнена белыми
# маргаритками, чем при `init_white = 0.2`.
#
# Параметр `max_age` определяет максимально допустимый возраст
# агентов и поэтому влияет на дальнейшую динамику популяции.
# Сравнение изображений после нескольких модельных шагов позволяет
# проследить, как изменение этого параметра отражается на
# сохранении и изменении количества маргариток.
#
# Во всех случаях тепловая карта позволяет одновременно наблюдать
# изменение температурного поля поверхности и пространственное
# распределение агентов.

# ## Вывод
#
# Параметрический эксперимент показывает, что модель Daisyworld
# может исследоваться не только для одного фиксированного набора
# параметров, но и для нескольких их комбинаций.
#
# Изменение начальной доли белых маргариток существенно изменяет
# начальное состояние системы, а изменение максимального возраста
# агентов влияет на последующую динамику популяции.
#
# Использование `dict_list` и `savename` позволяет автоматизировать
# серию вычислительных экспериментов и сохранять результаты таким
# образом, чтобы каждый файл был связан с конкретным набором
# параметров модели.
