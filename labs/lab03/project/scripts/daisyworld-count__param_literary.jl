# # Динамика числа маргариток для набора параметров
#
# В данном эксперименте исследуется изменение численности
# чёрных и белых маргариток во времени для нескольких
# комбинаций параметров модели Daisyworld.
#
# Для каждой комбинации параметров модель выполняется
# в течение 1000 модельных шагов, после чего строится
# отдельный график динамики двух популяций.

using DrWatson
@quickactivate "project"
using Agents
using DataFrames
using Plots
using CairoMakie
include(srcdir("daisyworld.jl"))

# ## Определение типов маргариток
#
# Определяем функции, позволяющие определить тип каждого агента.
# Они используются при сборе данных о количестве маргариток.

black(a) = a.breed == :black
white(a) = a.breed == :white

# Указываем данные, которые необходимо собирать во время
# выполнения модели: количество чёрных и белых маргариток.

adata = [(black, count), (white, count)]

# ## Параметры эксперимента
#
# Создаём словарь параметров модели.
#
# В эксперименте изменяются два параметра:
#
# - `max_age` принимает значения 25 и 40;
# - `init_white` принимает значения 0.2 и 0.8.
#
# Остальные параметры остаются постоянными.

param_dict = Dict(
:griddims => (30, 30),
:max_age => [25, 40],
:init_white => [0.2, 0.8],
:init_black => 0.2,
:albedo_white => 0.75,
:albedo_black => 0.25,
:surface_albedo => 0.4,
:solar_change => 0.005,
:solar_luminosity => 1.0,
:scenario => :default,
:seed => 165,
)

# ## Формирование комбинаций параметров
#
# С помощью функции `dict_list` формируем все возможные
# комбинации значений параметров.
#
# Поскольку `max_age` имеет два значения и `init_white`
# также имеет два значения, всего формируется четыре
# набора параметров.

params_list = dict_list(param_dict)

# ## Выполнение серии экспериментов
#
# Для каждого набора параметров создаётся отдельная модель.
# Модель выполняется в течение 1000 шагов, после чего
# строится график изменения количества чёрных и белых
# маргариток.
#
# Вся конструкция `for ... end` оставлена единым блоком,
# что важно при последующей генерации Jupyter notebook.

for params in params_list

    model = daisyworld(;params...)

    agent_df, model_df = run!(model, 1000; adata)

    figure = Figure(size = (600, 400));

    ax = figure[1, 1] = Axis(
        figure,
        xlabel = "tick",
        ylabel = "daisy count"
    )

    blackl = lines!(
        ax,
        agent_df[!, :time],
        agent_df[!, :count_black],
        color = :black
    )

    whitel = lines!(
        ax,
        agent_df[!, :time],
        agent_df[!, :count_white],
        color = :orange
    )

    Legend(
        figure[1, 2],
        [blackl, whitel],
        ["black", "white"],
        labelsize = 12
    )

    plt_name = savename("daisy-count",params)

    save(plotsdir(plt_name * ".png"), figure)

end

# ## Анализ результата
#
# В результате эксперимента получены графики динамики
# численности чёрных и белых маргариток для четырёх
# комбинаций параметров:
#
# - `max_age = 25`, `init_white = 0.2`;
# - `max_age = 40`, `init_white = 0.2`;
# - `max_age = 25`, `init_white = 0.8`;
# - `max_age = 40`, `init_white = 0.8`.
#
# Для каждого набора параметров модель выполнялась
# в течение 1000 модельных шагов.
#
# Значение `init_white` определяет начальную долю белых
# маргариток. Поэтому при `init_white = 0.8` белая
# популяция в начале моделирования значительно больше,
# чем при `init_white = 0.2`.
#
# Параметр `max_age` задаёт максимальный возраст агента.
# Изменение этого параметра влияет на продолжительность
# существования отдельных маргариток и, следовательно,
# на дальнейшую динамику численности популяций.
#
# Графики позволяют сравнить не только абсолютное количество
# маргариток, но и характер колебаний популяций при различных
# сочетаниях параметров.
#
# Использование одинакового значения `seed = 165` обеспечивает
# воспроизводимость вычислительного эксперимента.

# ## Вывод
#
# Параметрический эксперимент показывает, что динамика
# популяций Daisyworld зависит от выбранных параметров модели.
#
# Изменение начальной доли белых маргариток непосредственно
# влияет на начальное соотношение популяций, а изменение
# максимального возраста агентов влияет на дальнейшее
# развитие и устойчивость их численности.
#
# Проведение серии экспериментов для нескольких комбинаций
# параметров позволяет сравнивать различные режимы поведения
# системы и оценивать влияние параметров на динамику
# чёрных и белых маргариток.
#
# Использование функций `dict_list` и `savename` из DrWatson
# автоматизирует выполнение серии экспериментов и связывает
# каждый сохранённый график с конкретным набором параметров.
