#
# Итоговый график позволяет сравнить динамику состояния
# `Eat_i` для всех пяти философов в двух вариантах сети Петри.
#
# Классическая сеть используется для наблюдения поведения системы
# без дополнительного ограничения на захват ресурсов.
#
# Сеть с арбитром позволяет исследовать влияние дополнительного
# механизма синхронизации на последовательность состояний философов
# и сравнить её с классическим вариантом.
#
# Полученный рисунок может быть использован в итоговом отчёте
# лабораторной работы как сравнительная визуализация двух моделей.
