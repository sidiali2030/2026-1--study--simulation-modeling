# # Сравнительный анализ классической сети и сети с арбитром
#
# В данном скрипте выполняется сравнительный анализ результатов
# моделирования задачи обедающих философов для двух вариантов
# сети Петри:
#
# 1. классической сети без арбитра;
# 2. сети с арбитром.
#
# Для анализа используются ранее сохранённые CSV-файлы.
# Основное внимание уделяется состоянию `Eat_i`, которое показывает,
# находится ли соответствующий философ в состоянии приёма пищи.

# ## Подключение рабочего окружения
#
# Активируем окружение проекта DrWatson и подключаем библиотеки
# для работы с таблицами, CSV-файлами и построения графиков.

using DrWatson
@quickactivate "project"

using DataFrames, CSV, Plots

# ## Загрузка результатов моделирования
#
# Загружаем результаты классической сети Петри и сети с арбитром.
#
# Файлы были получены на предыдущем этапе моделирования и содержат
# временную динамику маркировок всех позиций сети.

df_classic = CSV.read(
    datadir("dining_classic.csv"),
    DataFrame,
)

df_arbiter = CSV.read(
    datadir("dining_arbiter.csv"),
    DataFrame,
)

# ## Количество философов
#
# В рассматриваемой модели используется пять философов.

N = 5

# ## Выбор позиций состояния «Ест»
#
# Для каждого философа в сети существует позиция `Eat_i`,
# которая принимает значение 1, когда философ ест,
# и 0 — в остальных состояниях.
#
# Формируем список соответствующих столбцов таблицы:
#
# `Eat_1`, `Eat_2`, ..., `Eat_5`.

eat_cols = [
    Symbol("Eat_$i")
    for i = 1:N
]

# # Классическая сеть Петри
#
# Строим временные зависимости состояния `Eat_i`
# для каждого философа в классической сети.
#
# По оси X откладывается модельное время,
# а по оси Y — значение позиции `Eat_i`.

p1 = plot(
    df_classic.time,
    Matrix(df_classic[:, eat_cols]),
    label = ["Ф $i" for i = 1:N],
    xlabel = "Время",
    ylabel = "Ест (1/0)",
    title = "Классическая сеть",
)

# # Сеть Петри с арбитром
#
# Аналогичным образом строим график для сети с арбитром.
#
# Это позволяет визуально сравнить поведение философов
# после введения дополнительного механизма синхронизации.

p2 = plot(
    df_arbiter.time,
    Matrix(df_arbiter[:, eat_cols]),
    label = ["Ф $i" for i = 1:N],
    xlabel = "Время",
    ylabel = "Ест (1/0)",
    title = "Сеть с арбитром",
)

# ## Объединение графиков
#
# Для удобства сравнения объединяем оба графика
# в одну вертикальную композицию.
#
# Верхний график соответствует классической сети,
# нижний — сети с арбитром.

p_final = plot(
    p1,
    p2,
    layout = (2, 1),
    size = (800, 600),
)

# ## Сохранение итогового графика
#
# Итоговая визуализация сохраняется в каталоге `plots`
# под именем `final_report.png`.

savefig(
    plotsdir("final_report.png"),
)

# После завершения выводим сообщение о расположении
# сформированного графика.

println(
    "Отчёт сохранён в plots/final_report.png",
)

