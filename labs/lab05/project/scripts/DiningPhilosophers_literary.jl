# # Моделирование задачи обедающих философов с помощью сетей Петри
#
# В данной программе проводится сравнительное моделирование двух вариантов
# сети Петри для задачи обедающих философов:
#
# 1. классической сети без дополнительного механизма синхронизации;
# 2. модифицированной сети с арбитром.
#
# Для каждого варианта выполняется стохастическая симуляция, результаты
# сохраняются в CSV-файл, проверяется наличие взаимной блокировки
# (deadlock), а также строится график изменения маркировки сети во времени.

# ## Подключение рабочего окружения
#
# Активируем проект DrWatson и подключаем модуль с реализацией
# сетей Петри для задачи обедающих философов.

using DrWatson

@quickactivate "project"

include(srcdir("DiningPhilosophers.jl"))

using .DiningPhilosophers

using DataFrames, CSV, Plots

# ## Параметры моделирования
#
# В классической постановке рассматриваются пять философов.
# Продолжительность стохастического моделирования зададим равной
# 50 единицам модельного времени.

N = 5
tmax = 50.0

# # Классическая сеть Петри
#
# Сначала исследуем классический вариант задачи без арбитра.
# Такая схема допускает возникновение взаимной блокировки, когда
# каждый философ удерживает одну вилку и ожидает освобождения второй.

println("=== Классическая сеть (без арбитра) ===")

# ## Построение сети
#
# Функция `build_classical_network` формирует сеть Петри для `N`
# философов и возвращает объект сети, начальную маркировку и имена
# позиций.

net_classic, u0_classic, _ = build_classical_network(N)

# ## Стохастическое моделирование
#
# Выполняем стохастическую симуляцию классической сети до момента
# `tmax`. Полученные маркировки сохраняются в таблице `DataFrame`.

df_classic = simulate_stochastic(net_classic, u0_classic, tmax)

# ## Сохранение результатов
#
# Результаты классического варианта сохраняются в CSV-файл
# `data/dining_classic.csv`.

CSV.write(datadir("dining_classic.csv"), df_classic)

# ## Проверка взаимной блокировки
#
# С помощью функции `detect_deadlock` проверяем, достигла ли сеть
# состояния, в котором дальнейшее срабатывание переходов невозможно.

dead = detect_deadlock(df_classic, net_classic)

println("Deadlock обнаружен: $dead")

# ## Визуализация динамики
#
# Строим график изменения маркировки классической сети во времени
# и сохраняем его в каталоге `plots`.

plot_classic = plot_marking_evolution(df_classic, N)

savefig(plotsdir("classic_simulation.png"))

# # Сеть Петри с арбитром
#
# Далее исследуем модифицированный вариант сети. В него вводится
# дополнительный арбитр, ограничивающий число философов, которые
# могут одновременно приступать к захвату ресурсов.
#
# Это позволяет предотвратить ситуацию, при которой все философы
# одновременно удерживают по одной вилке.

println("\n=== Сеть с арбитром ===")

# ## Построение сети с арбитром
#
# Функция `build_arbiter_network` создаёт сеть Петри с дополнительной
# позицией, представляющей ресурс арбитра.

net_arb, u0_arb, _ = build_arbiter_network(N)

# ## Стохастическое моделирование
#
# Запускаем моделирование сети с арбитром с той же продолжительностью,
# что и для классической сети.

df_arb = simulate_stochastic(net_arb, u0_arb, tmax)

# ## Сохранение результатов
#
# Таблица результатов сохраняется в файл
# `data/dining_arbiter.csv`.

CSV.write(datadir("dining_arbiter.csv"), df_arb)

# ## Проверка взаимной блокировки
#
# Проверяем наличие deadlock для сети с арбитром.

dead_arb = detect_deadlock(df_arb, net_arb)

println("Deadlock обнаружен: $dead_arb")

# ## Визуализация
#
# Строим график изменения маркировки сети с арбитром и сохраняем его
# отдельно для последующего сравнения с классическим вариантом.

plot_arb = plot_marking_evolution(df_arb, N)

savefig(plotsdir("arbiter_simulation.png"))

# # Вывод
#
# В результате выполнения программы получены два стохастических
# эксперимента для одной и той же задачи.
#
# Классическая сеть позволяет исследовать возможность возникновения
# взаимной блокировки при конкурентном доступе философов к вилкам.
#
# Вариант с арбитром вводит дополнительное ограничение на захват
# ресурсов и используется как механизм предотвращения deadlock.
#
# Полученные CSV-файлы и графики позволяют сравнить динамику
# маркировок двух вариантов сети Петри и оценить эффективность
# введения арбитра.
