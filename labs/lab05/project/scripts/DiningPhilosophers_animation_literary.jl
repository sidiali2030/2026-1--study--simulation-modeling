# # Анимация сети Петри для задачи обедающих философов
#
# В данном примере создаётся анимация изменения маркировки
# классической сети Петри для задачи обедающих философов.
#
# Для уменьшения числа отображаемых позиций используется сеть
# из трёх философов. Стохастическая симуляция выполняется
# в течение 30 единиц модельного времени.
#
# На каждом кадре анимации отображается текущее количество
# фишек в каждой позиции сети Петри.

# ## Подключение рабочего окружения
#
# Активируем окружение проекта DrWatson и подключаем модуль
# `DiningPhilosophers`, содержащий функции построения сети
# и стохастического моделирования.

using DrWatson

@quickactivate "project"

include(srcdir("DiningPhilosophers.jl"))

using .DiningPhilosophers

# Для визуализации используется пакет `Plots`, а пакет `Random`
# необходим для задания фиксированного зерна генератора
# случайных чисел.

using Plots, Random

# ## Параметры моделирования
#
# В данной визуализации рассматриваются три философа.
# Длительность моделирования составляет 30 единиц времени.

N = 3
tmax = 30.0

# ## Построение классической сети Петри
#
# С помощью функции `build_classical_network` создаём
# классическую сеть Петри без арбитра.
#
# Функция возвращает:
#
# - `net` — структуру сети Петри;
# - `u0` — начальную маркировку;
# - `names` — имена позиций сети.

net, u0, names = build_classical_network(N)

# ## Настройка воспроизводимости
#
# Поскольку стохастическая симуляция использует случайные числа,
# задаём фиксированное зерно генератора. Это позволяет получать
# одинаковую траекторию при повторном запуске программы.

Random.seed!(123)

# ## Стохастическая симуляция
#
# Выполняем моделирование классической сети Петри
# до момента времени `tmax`.
#
# Результат сохраняется в таблицу `df`, где каждая строка
# соответствует одной маркировке сети в определённый момент времени.

df = simulate_stochastic(net, u0, tmax)

# # Создание анимации
#
# Для каждой строки таблицы результатов создаётся отдельный кадр.
#
# Значения всех колонок, кроме `time`, представляют количество
# фишек в соответствующих позициях сети.

anim = @animate for row in eachrow(df)

    u = [
        row[col]
        for col in propertynames(row)
        if col != :time
    ]

    

    bar(
        1:length(u),
        u,
        legend = false,
        ylims = (0, maximum(u0) + 1),
        xlabel = "Позиция",
        ylabel = "Фишки",
        title = "Время = $(round(row.time, digits = 2))",
    )

   

    xticks!(
        1:length(u),
        string.(names),
        rotation = 45,
    )

end

# ## Сохранение анимации
#
# Полученную последовательность кадров сохраняем в формате GIF.
# Частота воспроизведения составляет два кадра в секунду.
#
# Итоговый файл создаётся в каталоге `plots/`.

gif(
    anim,
    plotsdir("philosophers_simulation.gif"),
    fps = 2,
)

# После завершения программы выводим путь к созданной анимации.

println(
    "Анимация сохранена в plots/philosophers_simulation.gif",
)

