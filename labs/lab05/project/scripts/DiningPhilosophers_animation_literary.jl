# показывающая изменение маркировки классической сети Петри
# во времени.
#
# Каждый кадр отражает количество фишек в отдельных позициях сети.
# Это позволяет визуально проследить переход философов между
# состояниями и изменение доступности вилок в ходе стохастической
# симуляции.
