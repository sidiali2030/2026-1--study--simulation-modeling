# # Комплексный анализ результатов сканирования β
#
# В данном разделе выполняется итоговый анализ результатов
# параметрического исследования коэффициента заразности `β`.
#
# Результаты моделирования предварительно были сохранены
# в файл `beta_scan_all.csv`.
#
# На основе сохранённых данных строятся три графика:
#
# - пиковая и конечная доля инфицированных;
# - число умерших;
# - конечная доля выздоровевших.
#
# Это позволяет комплексно оценить влияние коэффициента
# заразности `β` на основные характеристики эпидемического процесса.

# ## Подключение библиотек
#
# Активируем окружение проекта DrWatson и подключаем библиотеки,
# необходимые для работы с табличными данными, загрузки CSV-файлов
# и визуализации результатов.

using DrWatson
@quickactivate "project"

using Agents
using DataFrames
using Plots
using CSV

# Подключаем реализацию агентной модели SIR.
#
# В данном скрипте модель повторно не запускается, однако файл
# подключается для сохранения общей структуры проекта.

include(srcdir("sir_model.jl"))

# ## Загрузка результатов экспериментов
#
# Загружаем результаты сканирования коэффициента `β`,
# ранее сохранённые в файл `data/beta_scan_all.csv`.

df = CSV.read(
    datadir("beta_scan_all.csv"),
    DataFrame,
)

# Выведем первые строки таблицы для проверки структуры данных.

first(df, 10)

# ## Анализ доли инфицированных
#
# Первый график показывает зависимость пикового значения
# доли инфицированных от коэффициента заразности `β`.

p1 = plot(
    df.beta,
    df.peak,
    label = "Пик",
    xlabel = "β",
    ylabel = "Доля инфицированных",
)

# На тот же график добавляем конечную долю инфицированных.
#
# Это позволяет сравнить максимальный уровень распространения
# инфекции с состоянием системы в конце моделирования.

plot!(
    p1,
    df.beta,
    df.final_inf,
    label = "Конечная",
)

# ## Анализ смертности
#
# Второй график отражает зависимость общего числа умерших
# от значения коэффициента заразности `β`.

p2 = plot(
    df.beta,
    df.deaths,
    xlabel = "β",
    ylabel = "Число умерших",
    label = "Умершие",
)

# ## Анализ выздоровления
#
# Третий график показывает конечную долю выздоровевших агентов
# при различных значениях коэффициента заразности.

p3 = plot(
    df.beta,
    df.final_rec,
    xlabel = "β",
    ylabel = "Доля выздоровевших",
    label = "Выздоровевшие",
)

# ## Формирование составного графика
#
# Объединяем три полученных графика в одну вертикальную композицию.
#
# Такая форма представления позволяет одновременно сравнить
# изменение основных эпидемиологических показателей при росте `β`.

combined_plot = plot(
    p1,
    p2,
    p3,
    layout = (3, 1),
    size = (800, 900),
)

# Отображаем составной график.

combined_plot

# ## Сохранение результата
#
# Сохраняем итоговую визуализацию в каталог `plots`.

savefig(
    combined_plot,
    plotsdir("comprehensive_analysis.png"),
)

# ## Результат анализа
#
# В результате формируется файл:
#
# `plots/comprehensive_analysis.png`
#
# Он содержит три взаимосвязанных графика, отражающих влияние
# коэффициента заразности на пиковую и конечную заболеваемость,
# смертность и долю выздоровевших агентов.

println(
    "Комплексный анализ сохранён в " *
    "plots/comprehensive_analysis.png",
)

# ## Вывод
#
# Проведён комплексный анализ результатов параметрического
# исследования коэффициента заразности `β`.
#
# Совместное рассмотрение пикового уровня инфекции,
# конечной доли инфицированных, числа умерших и доли
# выздоровевших позволяет оценить влияние изменения
# интенсивности передачи инфекции на динамику агентной
# модели SIR.
#
# Полученная визуализация объединяет основные показатели
# эксперимента и может использоваться для итогового сравнения
# результатов в отчёте по лабораторной работе.
