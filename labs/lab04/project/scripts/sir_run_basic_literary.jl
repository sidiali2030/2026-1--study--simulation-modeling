# # Базовый эксперимент агентной модели SIR
#
# В данном эксперименте выполняется базовый запуск агентной
# эпидемиологической модели SIR. Популяция распределена между
# тремя локациями. Каждый агент может находиться в одном из
# трёх состояний:
#
# - `S` (`Susceptible`) — восприимчивый;
# - `I` (`Infected`) — инфицированный;
# - `R` (`Recovered`) — выздоровевший.
#
# В ходе моделирования отслеживается изменение численности
# восприимчивых, инфицированных и выздоровевших агентов,
# а также общей численности популяции.

# ## Подключение библиотек
#
# Активируем окружение проекта DrWatson и подключаем библиотеки,
# необходимые для работы с агентной моделью, табличными данными,
# визуализацией и сохранением результатов.

using DrWatson
@quickactivate "project"

using Agents
using DataFrames
using Plots
using JLD2

# Подключаем реализацию агентной модели SIR.

include(srcdir("sir_model.jl"))

# ## Параметры эксперимента
#
# Параметры модели объединяем в словарь `params`.
#
# Используются следующие значения:
#
# - `Ns` — численность населения в каждой из трёх локаций;
# - `β_und` — интенсивность передачи инфекции невыявленными
#   инфицированными;
# - `β_det` — интенсивность передачи инфекции выявленными
#   инфицированными;
# - `infection_period` — продолжительность заболевания;
# - `detection_time` — время до выявления инфекции;
# - `death_rate` — вероятность смерти;
# - `reinfection_probability` — вероятность повторного заражения;
# - `Is` — начальное количество инфицированных в каждой локации;
# - `seed` — зерно генератора случайных чисел;
# - `n_steps` — продолжительность моделирования.

params = Dict(
    :Ns => [1000, 1000, 1000],
    :β_und => [0.5, 0.5, 0.5],
    :β_det => [0.05, 0.05, 0.05],
    :infection_period => 14,
    :detection_time => 7,
    :death_rate => 0.02,
    :reinfection_probability => 0.1,
    :Is => [0, 0, 1],
    :seed => 42,
    :n_steps => 100,
)

# Таким образом, начальная популяция состоит из 3000 агентов,
# распределённых поровну между тремя локациями. В начальный
# момент времени один инфицированный агент находится в третьей
# локации.

# ## Инициализация модели
#
# Создаём агентную модель SIR с заданными параметрами.

model = initialize_sir(; params...)

# ## Подготовка данных
#
# Для анализа динамики модели создаём массивы, в которые после
# каждого шага будут записываться модельное время и численности
# агентов в различных состояниях.

times = Int[]
S_vals = Int[]
I_vals = Int[]
R_vals = Int[]
total_vals = Int[]

# ## Запуск моделирования
#
# Выполняем симуляцию в течение `n_steps` шагов.
# Один шаг модели соответствует одному дню.
#
# После каждого шага определяем:
#
# - количество восприимчивых агентов;
# - количество инфицированных;
# - количество выздоровевших;
# - общую численность агентов.

for step = 1:params[:n_steps]
    Agents.step!(model, 1)

    push!(times, step)
    push!(S_vals, susceptible_count(model))
    push!(I_vals, infected_count(model))
    push!(R_vals, recovered_count(model))
    push!(total_vals, total_count(model))
end

# ## Формирование таблиц результатов
#
# Полученные значения преобразуем в объекты `DataFrame`.
# В таблице `agent_df` хранится динамика состояний агентов,
# а в `model_df` — изменение общей численности популяции.

agent_df = DataFrame(
    time = times,
    susceptible = S_vals,
    infected = I_vals,
    recovered = R_vals,
)

model_df = DataFrame(
    time = times,
    total = total_vals,
)

# Выведем первые строки таблицы с результатами моделирования.

first(agent_df, 10)

# ## Визуализация динамики эпидемии
#
# Построим график изменения численности восприимчивых,
# инфицированных и выздоровевших агентов во времени.
# Дополнительно пунктирной линией покажем общую численность
# агентов модели.

plot(
    agent_df.time,
    agent_df.susceptible,
    label = "Восприимчивые",
    xlabel = "Дни",
    ylabel = "Количество",
)

plot!(
    agent_df.time,
    agent_df.infected,
    label = "Инфицированные",
)

plot!(
    agent_df.time,
    agent_df.recovered,
    label = "Выздоровевшие",
)

plot!(
    agent_df.time,
    model_df.total,
    label = "Всего (включая умерших)",
    linestyle = :dash,
)

# Сохраняем построенный график в каталоге `plots`.

savefig(plotsdir("sir_basic_dynamics.png"))

# ## Сохранение результатов
#
# Для последующего анализа сохраняем таблицы с результатами
# моделирования в формате JLD2.

@save datadir("sir_basic_agent.jld2") agent_df
@save datadir("sir_basic_model.jld2") model_df

