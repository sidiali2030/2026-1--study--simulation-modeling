# распространения инфекции в агентной модели SIR.
# Моделирование позволяет проследить изменение количества
# восприимчивых, инфицированных и выздоровевших агентов
# на протяжении 100 модельных дней.
#
# График `sir_basic_dynamics.png` позволяет визуально оценить
# развитие эпидемического процесса, включая рост и снижение
# числа инфицированных и переход агентов в состояние
# выздоровевших. Изменение общей численности популяции
# отражает влияние смертности, предусмотренной моделью.
