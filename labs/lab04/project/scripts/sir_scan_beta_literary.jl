# # Исследование влияния коэффициента заразности β
#
# В данном эксперименте исследуется влияние коэффициента заразности
# `β` на динамику агентной эпидемиологической модели SIR.
#
# Для каждого значения коэффициента `β` выполняется несколько
# независимых прогонов модели с различными значениями зерна генератора
# случайных чисел (`seed`). Такой подход позволяет учитывать
# стохастический характер агентной модели.
#
# В ходе эксперимента определяются следующие показатели:
#
# - максимальная доля инфицированных агентов (`peak`);
# - конечная доля инфицированных (`final_inf`);
# - конечная доля выздоровевших (`final_rec`);
# - общее количество умерших (`deaths`).
#
# После выполнения всех экспериментов результаты усредняются
# для каждого значения `β` и визуализируются.

# ## Подключение библиотек
#
# Активируем окружение проекта DrWatson и подключаем библиотеки,
# необходимые для агентного моделирования, обработки табличных данных,
# визуализации и сохранения результатов.

using DrWatson
@quickactivate "project"

using Agents
using DataFrames
using Plots
using CSV
using Random
using Statistics

# Подключаем реализацию агентной модели SIR.

include(srcdir("sir_model.jl"))

# ## Функция выполнения одного эксперимента
#
# Определим функцию `run_experiment`, которая получает словарь
# параметров одного эксперимента, создаёт модель SIR, выполняет
# моделирование и возвращает основные эпидемиологические показатели.

function run_experiment(p)


    beta = p[:beta]

    β_und = fill(beta, 3)
    β_det = fill(beta / 10, 3)


    model = initialize_sir(
        ;
        Ns = p[:Ns],
        β_und = β_und,
        β_det = β_det,
        infection_period = p[:infection_period],
        detection_time = p[:detection_time],
        death_rate = p[:death_rate],
        reinfection_probability = p[:reinfection_probability],
        Is = p[:Is],
        seed = p[:seed],
        n_steps = p[:n_steps],
    )


    infected_fraction(model) =
        count(a.status == :I for a in allagents(model)) / nagents(model)

 
    peak_infected = 0.0


    for step = 1:p[:n_steps]

        agent_ids = collect(allids(model))

        for id in agent_ids

            agent = try
                model[id]
            catch
                nothing
            end

            if agent !== nothing
                sir_agent_step!(agent, model)
            end
        end


        frac = infected_fraction(model)

  
        if frac > peak_infected
            peak_infected = frac
        end
    end


    final_infected = infected_fraction(model)

    final_recovered =
        count(a.status == :R for a in allagents(model)) / nagents(model)


    total_deaths = sum(p[:Ns]) - nagents(model)


    return (
        peak = peak_infected,
        final_inf = final_infected,
        final_rec = final_recovered,
        deaths = total_deaths,
    )
end

# ## Диапазон исследуемых параметров
#
# Исследуем коэффициент заразности `β` в диапазоне от `0.1`
# до `1.0` с шагом `0.1`.

beta_range = 0.1:0.1:1.0

# Для каждого значения `β` выполняются три независимых прогона
# с различными значениями `seed`.

seeds = [42, 43, 44]

# Таким образом, всего будет выполнено:
#
# `10 значений β × 3 значения seed = 30 экспериментов`.

# ## Формирование набора параметров
#
# Создаём список словарей параметров для всех комбинаций
# коэффициента заразности и зерна генератора случайных чисел.

params_list = []

for b in beta_range
    for s in seeds
        push!(
            params_list,
            Dict(
                :beta => b,
                :Ns => [1000, 1000, 1000],
                :infection_period => 14,
                :detection_time => 7,
                :death_rate => 0.02,
                :reinfection_probability => 0.1,
                :Is => [0, 0, 1],
                :seed => s,
                :n_steps => 100,
            ),
        )
    end
end

# Проверим количество сформированных экспериментов.

length(params_list)

# ## Выполнение серии экспериментов
#
# Последовательно запускаем модель для каждого набора параметров.
# Полученные показатели объединяем с параметрами соответствующего
# эксперимента.

results = []

for params in params_list

    data = run_experiment(params)

    push!(
        results,
        merge(params, Dict(pairs(data))),
    )

    println(
        "Завершён эксперимент с beta = $(params[:beta]), " *
        "seed = $(params[:seed])",
    )
end

# ## Формирование таблицы результатов
#
# Результаты всех прогонов преобразуем в `DataFrame`.
# Каждая строка таблицы соответствует одному эксперименту.

df = DataFrame(results)

# Выведем первые строки полученной таблицы.

first(df, 10)

# ## Сохранение результатов
#
# Полные результаты всех прогонов сохраняются в CSV-файл.
# Это позволяет использовать их в дальнейшем анализе
# без повторного выполнения моделирования.

CSV.write(
    datadir("beta_scan_all.csv"),
    df,
)

# ## Усреднение результатов
#
# Поскольку для каждого значения `β` выполнялось три независимых
# прогона, сгруппируем результаты по коэффициенту заразности.
#
# Для каждого значения `β` вычисляем:
#
# - среднюю пиковую долю инфицированных;
# - среднюю конечную долю инфицированных;
# - среднее количество умерших.

grouped = combine(
    groupby(df, [:beta]),
    :peak => mean => :mean_peak,
    :final_inf => mean => :mean_final_inf,
    :deaths => mean => :mean_deaths,
)

# Выведем усреднённые результаты.

grouped

# ## Визуализация результатов
#
# Построим график зависимости основных эпидемиологических
# показателей от коэффициента заразности `β`.
#
# Первая линия показывает среднее максимальное значение
# доли инфицированных агентов.

plot(
    grouped.beta,
    grouped.mean_peak,
    label = "Пик эпидемии",
    xlabel = "Коэффициент заразности β",
    ylabel = "Доля инфицированных",
    marker = :circle,
    linewidth = 2,
)

# Добавим конечную долю инфицированных.

plot!(
    grouped.beta,
    grouped.mean_final_inf,
    label = "Конечная доля инфицированных",
    marker = :square,
)

# Количество умерших нормируем на начальную численность
# населения, равную 3000 агентам, и отображаем как долю.

plot!(
    grouped.beta,
    grouped.mean_deaths ./ 3000,
    label = "Доля умерших",
    marker = :diamond,
)

# Сохраняем итоговый график в каталоге `plots`.

savefig(
    plotsdir("beta_scan.png"),
)

