# # Исследование влияния интенсивности миграции
#
# В данном эксперименте исследуется влияние миграции агентов
# между различными локациями на динамику распространения инфекции
# в агентной модели SIR.
#
# Начальная популяция распределена между тремя локациями,
# при этом инфекция первоначально появляется только в первой
# локации. Интенсивность миграции изменяется от `0.0` до `0.5`.
#
# Для каждого значения интенсивности миграции выполняется несколько
# независимых прогонов модели с различными значениями `seed`.
#
# В ходе эксперимента определяются два основных показателя:
#
# - время достижения пика эпидемии (`peak_time`);
# - максимальная доля инфицированных агентов (`peak_value`).
#
# Полученные результаты позволяют оценить влияние перемещения
# агентов между локациями на скорость и интенсивность
# распространения инфекции.

# ## Подключение библиотек
#
# Активируем окружение проекта DrWatson и подключаем библиотеки,
# необходимые для агентного моделирования, обработки данных,
# статистического анализа, визуализации и сохранения результатов.

using DrWatson
@quickactivate "project"

using Agents
using DataFrames
using Plots
using CSV
using Random
using Statistics

# Подключаем реализацию агентной модели SIR.

include(srcdir("sir_model.jl"))

# ## Формирование матрицы миграции
#
# Для описания перемещения агентов между локациями определим
# функцию `create_migration_matrix`.
#
# Параметр `C` задаёт количество локаций, а `intensity` —
# общую интенсивность миграции.
#
# Диагональные элементы матрицы соответствуют вероятности
# остаться в текущей локации. Остальная вероятность равномерно
# распределяется между другими локациями.

function create_migration_matrix(C, intensity)

    M = ones(C, C) .* intensity ./ (C - 1)

    for i = 1:C
        M[i, i] = 1 - intensity
    end

    return M
end

# Например, при трёх локациях и интенсивности миграции `0.2`
# можно получить соответствующую матрицу переходов.

create_migration_matrix(3, 0.2)

# ## Определение времени достижения пика эпидемии
#
# Создадим функцию `peak_time`, которая выполняет один эксперимент
# с заданными параметрами и определяет момент достижения
# максимальной доли инфицированных агентов.

function peak_time(p)

    migration_rates =
        create_migration_matrix(
            p[:C],
            p[:migration_intensity],
        )

    model = initialize_sir(
        ;
        Ns = p[:Ns],
        β_und = p[:β_und],
        β_det = p[:β_det],
        infection_period = p[:infection_period],
        detection_time = p[:detection_time],
        death_rate = p[:death_rate],
        reinfection_probability = p[:reinfection_probability],
        Is = p[:Is],
        seed = p[:seed],
        migration_rates = migration_rates,
    )

    infected_frac(model) =
        count(a.status == :I for a in allagents(model)) / nagents(model)


    peak = 0.0
    peak_step = 0

    for step = 1:p[:n_steps]

        agent_ids = collect(allids(model))

        for id in agent_ids

            agent = try
                model[id]
            catch
                nothing
            end

            if agent !== nothing
                sir_agent_step!(agent, model)
            end
        end

        frac = infected_frac(model)


        if frac > peak
            peak = frac
            peak_step = step
        end
    end


    return (
        peak_time = peak_step,
        peak_value = peak,
    )
end

# ## Диапазон интенсивности миграции
#
# Исследуем значения интенсивности миграции от `0.0` до `0.5`
# с шагом `0.1`.

migration_intensities = 0.0:0.1:0.5

# Для каждого значения интенсивности выполняются три независимых
# прогона модели с различными значениями зерна генератора
# случайных чисел.

seeds = [42, 43, 44]

# Таким образом, всего выполняется:
#
# `6 значений интенсивности × 3 значения seed = 18 экспериментов`.

# ## Формирование набора параметров
#
# Создаём список параметров для всех комбинаций интенсивности
# миграции и значений `seed`.
#
# Начальная инфекция присутствует только в первой локации,
# что задаётся параметром `Is = [1, 0, 0]`.

params_list = []

for mig in migration_intensities
    for s in seeds

        push!(
            params_list,
            Dict(
                :migration_intensity => mig,
                :C => 3,
                :Ns => [1000, 1000, 1000],
                :β_und => [0.5, 0.5, 0.5],
                :β_det => [0.05, 0.05, 0.05],
                :infection_period => 14,
                :detection_time => 7,
                :death_rate => 0.02,
                :reinfection_probability => 0.1,
                :Is => [1, 0, 0],
                :seed => s,
                :n_steps => 150,
            ),
        )
    end
end

# Проверим количество сформированных экспериментов.

length(params_list)

# ## Выполнение серии экспериментов
#
# Для каждого набора параметров запускаем функцию `peak_time`.
# Полученные показатели объединяются с параметрами соответствующего
# эксперимента и сохраняются в общем массиве результатов.

results = []

for params in params_list

    data = peak_time(params)

    push!(
        results,
        merge(params, Dict(pairs(data))),
    )

    println(
        "Завершён эксперимент с migration_intensity = " *
        "$(params[:migration_intensity]), seed = $(params[:seed])",
    )
end

# ## Формирование таблицы результатов
#
# Результаты всех отдельных прогонов преобразуем в `DataFrame`.
# Каждая строка таблицы соответствует одному запуску модели.

df = DataFrame(results)

# Выведем первые строки полученной таблицы.

first(df, 10)

# ## Сохранение результатов
#
# Полные результаты всех экспериментов сохраняем в CSV-файл
# для последующего анализа без необходимости повторного
# выполнения моделирования.

CSV.write(
    datadir("migration_scan_all.csv"),
    df,
)

# ## Усреднение результатов
#
# Поскольку для каждого значения интенсивности миграции
# выполняется три независимых прогона, группируем результаты
# по параметру `migration_intensity`.
#
# Для каждой группы рассчитываем:
#
# - среднее время достижения пика эпидемии;
# - среднюю максимальную долю инфицированных.

grouped = combine(
    groupby(df, [:migration_intensity]),
    :peak_time => mean => :mean_peak_time,
    :peak_value => mean => :mean_peak_value,
)

# Выведем таблицу усреднённых результатов.

grouped

# ## Визуализация результатов
#
# Построим график зависимости времени достижения пика
# эпидемии от интенсивности миграции.

plot(
    grouped.migration_intensity,
    grouped.mean_peak_time,
    marker = :circle,
    xlabel = "Интенсивность миграции",
    ylabel = "Время до пика (дни)",
    label = "Время пика",
)

# Добавим на график пиковую заболеваемость.
#
# Значение `mean_peak_value` представляет долю инфицированных.
# Для отображения приблизительной численности инфицированных
# эта величина умножается на начальную численность популяции,
# равную 3000 агентов.

plot!(
    grouped.migration_intensity,
    grouped.mean_peak_value .* 3000,
    marker = :square,
    xlabel = "Интенсивность миграции",
    ylabel = "Численность в пике",
    label = "Пиковая заболеваемость",
)

# Сохраняем итоговый график в каталоге `plots`.

savefig(
    plotsdir("migration_effect.png"),
)

