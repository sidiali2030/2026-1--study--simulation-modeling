using DrWatson
@quickactivate "project"

include(srcdir("sir_model_vaccination.jl"))

using Random
using StatsPlots
using DataFrames


# ============================================================
# Параметры модели
# ============================================================

tmax = 40.0

u0 = [990, 10, 0]

p = [0.05, 10.0, 0.25]


# ============================================================
# Параметры вакцинации
# ============================================================

vaccination_time = 10.0

vaccination_fraction = 0.50


# ============================================================
# Фиксируем seed
# ============================================================

Random.seed!(1234)


# ============================================================
# Создаём модель
# ============================================================

model = MakeSIRModel(
    u0,
    p
)


# ============================================================
# Активируем процессы индивидов
# ============================================================

activate(model)


# ============================================================
# Планируем событие вакцинации
# ============================================================

activate_vaccination!(
    model,
    vaccination_time,
    vaccination_fraction
)


# ============================================================
# Запускаем симуляцию
# ============================================================

sir_run(
    model,
    tmax
)


# ============================================================
# Получаем результаты
# ============================================================

data_vaccination = out(model)


# ============================================================
# Вывод основных результатов
# ============================================================

println()
println("========================================")
println("РЕЗУЛЬТАТЫ")
println("========================================")

println("Время вакцинации = ", vaccination_time)

println(
    "Доля вакцинации = ",
    vaccination_fraction * 100,
    "%"
)

println(
    "Максимальное число инфицированных = ",
    maximum(data_vaccination.I)
)

println(
    "Конечное S = ",
    data_vaccination.S[end]
)

println(
    "Конечное I = ",
    data_vaccination.I[end]
)

println(
    "Конечное R = ",
    data_vaccination.R[end]
)


# ============================================================
# График
# ============================================================

plt = @df data_vaccination plot(
    :t,
    [:S :I :R],

    labels = [
        "S"
        "I"
        "R"
    ],

    xlabel = "Время",
    ylabel = "Численность",

    title = "SIR модель с вакцинацией",

    linewidth = 2,

    size = (900, 600)
)


# Момент вакцинации
vline!(
    plt,
    [vaccination_time],

    linestyle = :dash,

    label = "Вакцинация"
)


# ============================================================
# Сохранение
# ============================================================

savefig(
    plt,
    plotsdir("sir_vaccination.png")
)

println()
println(
    "График сохранён: ",
    plotsdir("sir_vaccination.png")
)
