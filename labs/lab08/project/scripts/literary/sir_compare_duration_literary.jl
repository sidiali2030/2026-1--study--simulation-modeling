# # Сравнение стохастической и детерминированной длительности болезни
#
# В данном эксперименте сравниваются два варианта
# дискретно-событийной SIR-модели:
#
# - модель со стохастической длительностью болезни;
# - модель с детерминированной длительностью болезни.
#
# В исходной модели время выздоровления является случайной величиной
# с экспоненциальным распределением:
#
# $$
# T_{\mathrm{rec}} \sim \mathrm{Exp}(\gamma).
# $$
#
# Средняя длительность болезни при этом равна
#
# $$
# E[T_{\mathrm{rec}}] = \frac{1}{\gamma}.
# $$
#
# Во втором варианте длительность болезни фиксирована и для каждого
# инфицированного индивида составляет
#
# $$
# T_{\mathrm{rec}} = \frac{1}{\gamma}.
# $$
#
# Для корректного сравнения обе модели запускаются с одинаковыми
# начальными условиями, параметрами и зерном генератора случайных чисел.

# ## Подключение проекта и библиотек
#
# Активируем окружение DrWatson и подключаем библиотеки,
# необходимые для генерации случайных чисел и построения графиков.

using DrWatson
@quickactivate "project"

using Random
using StatsPlots

# Подключаем две реализации SIR-модели.
#
# Файл `sir_model.jl` содержит исходную модель со случайной
# длительностью болезни, а `sir_model_fixed.jl` — модифицированный
# вариант с фиксированной длительностью болезни.

include(srcdir("sir_model.jl"))
include(srcdir("sir_model_fixed.jl"))

# ## Параметры эксперимента
#
# Продолжительность моделирования составляет 40 единиц
# модельного времени.

tmax = 40.0

# Начальное состояние популяции:
#
# $$
# u_0 = [S_0, I_0, R_0] = [990, 10, 0].
# $$
#
# Таким образом, в начальный момент времени имеются:
#
# - 990 восприимчивых;
# - 10 инфицированных;
# - 0 выздоровевших.

u0 = [
    990,
    10,
    0
]

# Параметры модели задаются вектором
#
# $$
# p = [\beta, c, \gamma],
# $$
#
# где:
#
# - `β` — вероятность передачи инфекции при контакте;
# - `c` — средняя частота контактов;
# - `γ` — интенсивность выздоровления.

p = [
    0.05,
    10.0,
    0.25
]

# При значении
#
# $$
# \gamma = 0.25
# $$
#
# средняя длительность болезни в стохастической модели
# и фиксированная длительность болезни во второй модели равны
#
# $$
# \frac{1}{\gamma} = 4.
# $$

# Для обеспечения воспроизводимости результатов зададим одинаковое
# зерно генератора случайных чисел для обоих вариантов модели.

seed = 1234

# ## Модель со стохастической длительностью болезни
#
# Сначала запускаем исходную SIR-модель.
#
# В ней длительность инфекционного периода определяется случайно
# с помощью экспоненциального распределения.

Random.seed!(seed)

stoch_model = MakeSIRModel(
    u0,
    p
)

# Активируем процессы всех индивидов.

activate(
    stoch_model
)

# Запускаем дискретно-событийную симуляцию.

sir_run(
    stoch_model,
    tmax
)

# Получаем результаты моделирования в виде таблицы.

data_stoch = out(
    stoch_model
)

# ## Модель с детерминированной длительностью болезни
#
# Теперь запускаем модифицированный вариант модели.
#
# Перед запуском снова устанавливаем то же самое зерно генератора
# случайных чисел. Это необходимо для более корректного сравнения
# двух вариантов модели.

Random.seed!(seed)

fixed_model = MakeSIRModelFixed(
    u0,
    p
)

# Активируем процессы модифицированной модели.

activate_fixed(
    fixed_model
)

# Выполняем моделирование до того же момента времени `tmax`.

sir_run_fixed(
    fixed_model,
    tmax
)

# Получаем результаты моделирования.

data_fixed = out_fixed(
    fixed_model
)

# ## Сравнение динамики эпидемии
#
# Для сравнения двух вариантов рассмотрим изменение числа
# инфицированных `I(t)`.
#
# Сначала построим кривую для модели со случайной длительностью
# болезни.

plt = plot(
    data_stoch.t,
    data_stoch.I,
    label = "I — случайная длительность",
    xlabel = "Время",
    ylabel = "Число инфицированных",
    title = "Сравнение длительности болезни",
    linewidth = 2,
)

# На тот же график добавим результаты модели с фиксированной
# длительностью инфекционного периода.
#
# Для визуального различия вторая кривая отображается
# штриховой линией.

plot!(
    plt,
    data_fixed.t,
    data_fixed.I,
    label = "I — фиксированная длительность",
    linewidth = 2,
    linestyle = :dash,
)

# ## Сохранение результата
#
# Полученный сравнительный график сохраняется в каталоге `plots`
# проекта DrWatson.

savefig(
    plt,
    plotsdir("sir_duration_comparison.png")
)

println("График сохранён:")
println(
    plotsdir("sir_duration_comparison.png")
)

# ## Вывод
#
# В ходе эксперимента были сопоставлены два варианта
# дискретно-событийной SIR-модели при одинаковых начальных условиях
# и параметрах.
#
# В стохастическом варианте длительность инфекционного периода
# различается между индивидами и определяется экспоненциальным
# распределением.
#
# В детерминированном варианте каждый инфицированный остаётся
# в состоянии `I` одинаковое время, равное `1/γ`.
#
# Сравнительный график позволяет оценить влияние характера
# длительности болезни на форму эпидемической кривой, величину
# пика числа инфицированных и время его достижения.
