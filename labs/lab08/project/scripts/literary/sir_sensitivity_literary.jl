# # Анализ чувствительности SIR-модели к параметру β
#
# В данном эксперименте исследуется чувствительность
# дискретно-событийной SIR-модели к изменению параметра `β`.
#
# Параметр `β` определяет вероятность передачи инфекции
# при контакте восприимчивого индивида с инфицированным.
#
# Для нескольких значений `β` выполняются отдельные запуски модели,
# после чего оцениваются основные характеристики эпидемии:
#
# - максимальное число инфицированных;
# - время достижения максимума;
# - конечное число выздоровевших.
#
# Для корректного сравнения при каждом запуске используется
# одинаковое зерно генератора случайных чисел.

# ## Подключение проекта и библиотек
#
# Активируем окружение DrWatson и подключаем реализацию
# дискретно-событийной SIR-модели.

using DrWatson
@quickactivate "project"

include(srcdir("sir_model.jl"))

# Подключаем библиотеки для работы со случайными числами,
# табличными данными и визуализацией.

using Random
using DataFrames
using StatsPlots

# ## Параметры моделирования
#
# Продолжительность каждого эксперимента составляет
# 40 единиц модельного времени.

tmax = 40.0

# Начальное состояние задаётся вектором
#
# $$
# u_0 = [S_0, I_0, R_0].
# $$
#
# В начальный момент времени имеются:
#
# - 990 восприимчивых;
# - 10 инфицированных;
# - 0 выздоровевших.

u0 = [
    990,
    10,
    0
]

# ## Исследуемые значения β
#
# Для анализа чувствительности рассмотрим три значения
# вероятности передачи инфекции:
#
# $$
# \beta \in \{0.03,\;0.05,\;0.07\}.
# $$

betas = [
    0.03,
    0.05,
    0.07
]

# При этом остальные параметры модели остаются неизменными:
#
# $$
# c = 10,
# \qquad
# \gamma = 0.25.
# $$
#
# Таким образом, между экспериментами изменяется только `β`.

# ## Проведение серии экспериментов
#
# Последовательно выполняем моделирование для каждого значения `β`.

for β in betas


    Random.seed!(1234)

    p = [
        β,
        10.0,
        0.25
    ]


    m = MakeSIRModel(
        u0,
        p
    )


    activate(m)

  
    sir_run(
        m,
        tmax
    )


    data = out(m)


    peak_I = maximum(
        data.I
    )

    peak_index = argmax(
        data.I
    )


    peak_time =
        data.t[peak_index]


    final_R =
        data.R[end]

    println(
        "β = $β, ",
        "peak I = $peak_I, ",
        "peak time = $peak_time, ",
        "final R = $final_R"
    )

    pfig = @df data plot(
        :t,
        [:S :I :R],
        label = ["S" "I" "R"],
        xlabel = "Время",
        ylabel = "Численность",
        title = "β = $β"
    )

    savefig(
        pfig,
        plotsdir(
            "sir_beta_$β.png"
        )
    )
end

# ## Результаты эксперимента
#
# После выполнения цикла будут проведены три эксперимента:
#
# | β | Результирующий график |
# |---:|:---|
# | 0.03 | `sir_beta_0.03.png` |
# | 0.05 | `sir_beta_0.05.png` |
# | 0.07 | `sir_beta_0.07.png` |
#
# Для каждого эксперимента в консоли также выводятся
# максимальное число инфицированных, время достижения пика
# и конечное число выздоровевших.

# ## Вывод
#
# Проведён анализ чувствительности дискретно-событийной
# SIR-модели к изменению вероятности передачи инфекции `β`.
#
# Использование нескольких значений параметра при неизменных
# начальных условиях, параметрах `c` и `γ`, а также одинаковом
# зерне генератора случайных чисел позволяет сопоставить
# динамику эпидемического процесса между экспериментами.
#
# Полученные значения максимального числа инфицированных,
# времени достижения пика и конечного числа выздоровевших
# позволяют количественно оценить влияние параметра `β`
# на результаты моделирования.
