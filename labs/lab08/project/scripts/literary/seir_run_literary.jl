# # Дискретно-событийная модель SEIR
#
# В данной программе реализуется запуск дискретно-событийной
# эпидемиологической модели SEIR.
#
# Модель содержит четыре состояния:
#
# - `S` — восприимчивые;
# - `E` — инфицированные, находящиеся в латентном периоде;
# - `I` — инфекционные;
# - `R` — выздоровевшие.
#
# Переходы между состояниями происходят по схеме:
#
# $$
# S \rightarrow E \rightarrow I \rightarrow R.
# $$
#
# В отличие от модели SIR, после заражения индивид сначала переходит
# в состояние `E` и только после завершения латентного периода
# становится инфекционным.

# ## Подключение проекта и библиотек
#
# Активируем окружение DrWatson и подключаем реализацию модели
# из файла `src/seir_model.jl`.

using DrWatson
@quickactivate "project"

include(srcdir("seir_model.jl"))

using Random
using StatsPlots
using DataFrames

# ## Параметры моделирования
#
# Продолжительность моделирования составляет 40 единиц модельного времени.

tmax = 40.0

# Начальное состояние популяции задаётся вектором
#
# $$
# u_0 = [S_0, E_0, I_0, R_0].
# $$
#
# В начальный момент времени в популяции находятся:
#
# - 990 восприимчивых;
# - 0 индивидов в латентном состоянии;
# - 10 инфицированных;
# - 0 выздоровевших.

u0 = [
    990,
    0,
    10,
    0
]

# Параметры модели задаются вектором
#
# $$
# p = [\beta, c, \sigma, \gamma],
# $$
#
# где:
#
# - `β` — вероятность передачи инфекции при контакте;
# - `c` — средняя частота контактов;
# - `σ` — интенсивность перехода из состояния `E` в состояние `I`;
# - `γ` — интенсивность выздоровления.

p = [
    0.05,
    10.0,
    0.5,
    0.25
]

# При выбранных значениях параметров средний латентный период равен
#
# $$
# \frac{1}{\sigma} = 2,
# $$
#
# а средняя продолжительность инфекционного периода:
#
# $$
# \frac{1}{\gamma} = 4.
# $$

# ## Вывод исходных параметров
#
# Перед запуском симуляции выведем начальное состояние и параметры модели.

println("========================================")
println("SEIR МОДЕЛЬ")
println("========================================")

println("Начальное состояние:")
println("S0 = ", u0[1])
println("E0 = ", u0[2])
println("I0 = ", u0[3])
println("R0 = ", u0[4])

println()

println("Параметры:")
println("β = ", p[1])
println("c = ", p[2])
println("σ = ", p[3])
println("γ = ", p[4])

println(
    "Средний латентный период = ",
    1 / p[3]
)

println(
    "Средняя длительность болезни = ",
    1 / p[4]
)

# ## Фиксация генератора случайных чисел
#
# Поскольку модель является стохастической, фиксируем зерно генератора
# случайных чисел. Это позволяет получить воспроизводимый результат
# при повторном запуске программы.

Random.seed!(1234)

# ## Создание модели
#
# Создаём объект SEIR-модели на основе начального состояния `u0`
# и набора параметров `p`.

seir_model = MakeSEIRModel(
    u0,
    p
)

# ## Активация процессов
#
# Для каждого индивида регистрируется отдельный процесс
# дискретно-событийной симуляции.

activate(seir_model)

# ## Запуск симуляции
#
# Выполняем моделирование до момента времени `tmax`.

seir_run(
    seir_model,
    tmax
)

# ## Получение результатов
#
# После завершения симуляции преобразуем накопленные значения
# в таблицу `DataFrame`.

data_seir = out(seir_model)

# В таблице содержатся столбцы:
#
# - `t` — модельное время;
# - `S` — количество восприимчивых;
# - `E` — количество индивидов в латентном состоянии;
# - `I` — количество инфекционных;
# - `R` — количество выздоровевших.

# ## Расчёт показателей
#
# Для анализа динамики эпидемии определим максимальное число
# инфекционных индивидов.

peak_I = maximum(data_seir.I)

# Определяем индекс строки, в которой достигается максимум `I`.

peak_index = argmax(data_seir.I)

# По этому индексу находим время достижения эпидемического пика.

peak_time = data_seir.t[peak_index]

# Также сохраняем конечные значения всех четырёх состояний.

final_S = data_seir.S[end]
final_E = data_seir.E[end]
final_I = data_seir.I[end]
final_R = data_seir.R[end]

# ## Вывод результатов
#
# Выводим основные показатели проведённого эксперимента.

println()

println("========================================")
println("РЕЗУЛЬТАТЫ")
println("========================================")

println(
    "Максимальное число инфицированных = ",
    peak_I
)

println(
    "Время пика = ",
    round(
        peak_time,
        digits = 3
    )
)

println(
    "Конечное S = ",
    final_S
)

println(
    "Конечное E = ",
    final_E
)

println(
    "Конечное I = ",
    final_I
)

println(
    "Конечное R = ",
    final_R
)

# Поскольку в данной версии SEIR-модели рождения и смерти не учитываются,
# общая численность популяции должна оставаться постоянной.
#
# Проверим выполнение этого условия.

println(
    "Проверка населения = ",
    final_S +
    final_E +
    final_I +
    final_R
)

# ## Визуализация динамики SEIR
#
# Построим временные зависимости всех четырёх состояний модели.
#
# На графике:
#
# - `S(t)` показывает уменьшение числа восприимчивых;
# - `E(t)` отражает накопление индивидов в латентной стадии;
# - `I(t)` характеризует активную фазу эпидемии;
# - `R(t)` показывает рост числа выздоровевших.

plt = @df data_seir plot(
    :t,
    [:S :E :I :R],
    label = ["S" "E" "I" "R"],
    xlabel = "Время",
    ylabel = "Численность",
    title = "Дискретно-событийная SEIR модель",
    linewidth = 2,
    size = (900, 600)
)

# ## Сохранение графика
#
# Результирующий график сохраняется в каталоге `plots`
# проекта DrWatson.

savefig(
    plt,
    plotsdir("seir_des.png")
)

println()

println(
    "График сохранён: ",
    plotsdir("seir_des.png")
)

# ## Вывод
#
# В результате была выполнена дискретно-событийная симуляция модели SEIR.
# Добавление состояния `E` позволило явно учитывать латентный период
# заболевания.
#
# В отличие от модели SIR, заражённый индивид не становится инфекционным
# немедленно. Сначала он проходит стадию `E`, длительность которой задаётся
# параметром `σ`.
#
# Это приводит к задержке развития эпидемического процесса и изменению
# времени и величины пика числа инфекционных индивидов.
